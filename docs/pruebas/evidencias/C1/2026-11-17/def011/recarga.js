const { chromium, nuevo, URL } = require('./comun')
const PROD = 'Ibuprofeno 400 mg ' + Date.now() % 1000
;(async () => {
  const b = await chromium.launch()
  const luis = await nuevo(b, 'luis@quienlotiene.test')
  const botica = await nuevo(b, 'botica@quienlotiene.test')
  await botica.goto(URL + '/tienda/solicitudes')
  await luis.goto(URL + '/solicitudes/nueva'); await luis.waitForTimeout(1500)
  await luis.getByRole('textbox', { name: '¿Qué estás buscando?' }).fill(PROD)
  await luis.getByRole('radio', { name: 'Farmacia' }).check()
  await luis.getByRole('radio', { name: /^Casa/ }).check()
  await luis.getByRole('button', { name: 'Preguntar', exact: true }).click()
  await luis.waitForTimeout(2500)
  const urlSol = luis.url(); console.log('URL_SOLICITUD', urlSol)
  await botica.getByText(PROD).first().waitFor({ timeout: 20000 })
  await botica.getByRole('link', { name: `Tengo algo parecido: ${PROD}` }).click()
  await botica.waitForTimeout(1000)
  await botica.getByLabel('Precio por unidad').fill('7500')
  await botica.getByLabel('¿Qué ofreces en su lugar?').fill('Advil 400 mg, caja x 10')
  await botica.getByRole('button', { name: 'Enviar respuesta' }).click()
  await botica.waitForTimeout(3000)
  await luis.screenshot({ path: 'recarga/' + (process.env.TAG||'') + '1-antes.png', fullPage: true })
  console.log('ANTES:', (await luis.locator('main').innerText()).slice(0, 600))
  await luis.reload(); await luis.waitForTimeout(4000)
  console.log('URL despues', luis.url())
  await luis.screenshot({ path: 'recarga/' + (process.env.TAG||'') + '2-despues.png', fullPage: true })
  console.log('DESPUES:', (await luis.locator('body').innerText()).slice(0, 800))
  await b.close()
})().catch(e => { console.error('ERROR', e); process.exit(1) })
