// Re-prueba de DEF-005 a DEF-009 (16/11/2026, main 55ab5b6). Se corrió en dos partes: la primera llegó hasta
// DEF-007 con La 5 y la segunda siguió desde la solicitud ya respondida; este archivo junta las dos con los ajustes
// de navegación (volver a /solicitudes/{id} en lugar de atrás) y del nombre de la opción «Lo recojo en la tienda».
const { chromium, nuevo, cap, URL, caps } = require('./comun')
const fs = require('fs')
const { execSync } = require('child_process')
const out = {}
async function paso(nombre, fn) { try { await fn(); out[nombre] = out[nombre] ?? 'ok' } catch (e) { out[nombre] = 'FALLO: ' + e.message.split('\n')[0]; console.log('FALLO PASO', nombre, e.message.split('\n')[0]) } }
const textoMain = p => p.locator('main').innerText()
;(async () => {
  const b = await chromium.launch()
  const la5 = await nuevo(b, 'drogueria5@quienlotiene.test')
  const botica = await nuevo(b, 'botica@quienlotiene.test')
  for (const t of [la5, botica]) await t.goto(URL + '/tienda/solicitudes')
  const ana = await nuevo(b, 'ana@quienlotiene.test')
  await ana.goto(URL + '/solicitudes/nueva'); await ana.waitForTimeout(1500)

  await paso('DEF-005', async () => {
    // El producto tiene el foco al entrar; un toque real en «Preguntar» con el formulario vacío
    out.def005foco = await ana.evaluate(() => document.activeElement?.getAttribute('aria-label') || document.activeElement?.id || document.activeElement?.tagName)
    await ana.getByRole('button', { name: 'Preguntar', exact: true }).click()
    await ana.waitForTimeout(800)
    await cap(ana, 'def005-publicar-vacio', 'DEF-005: un solo toque en «Preguntar» con todo vacío marca producto y categoría, con el resumen')
    out.def005resumen = await ana.getByRole('heading', { name: 'Revisa estos datos antes de preguntar:' }).count()
    out.def005enlaces = await ana.getByRole('link').allInnerTexts()
    out.def005texto = await textoMain(ana)
  })
  await paso('publicar', async () => {
    await ana.getByRole('textbox', { name: '¿Qué estás buscando?' }).fill('Cetirizina 10 mg')
    await ana.getByRole('radio', { name: 'Farmacia' }).check()
    await ana.getByRole('radio', { name: /^Casa/ }).check()
    await ana.getByRole('radio', { name: 'Domicilio' }).check()
    await ana.getByRole('button', { name: 'Preguntar', exact: true }).click()
    await ana.waitForTimeout(2500)
    out.solicitudAna = execSync(`docker exec qa-db psql -U quienlotiene -d quienlotiene -tAc "select id from solicitudes.solicitud where producto='Cetirizina 10 mg'"`).toString().trim()
  })
  await paso('responder', async () => {
    await la5.getByText('Cetirizina 10 mg').first().waitFor({ timeout: 15000 })
    await la5.getByRole('link', { name: 'Sí lo tengo: Cetirizina 10 mg' }).click(); await la5.waitForTimeout(1000)
    await la5.getByLabel('Precio por unidad').fill('6000')
    await la5.getByRole('button', { name: 'Enviar respuesta' }).click(); await la5.waitForTimeout(1500)
    await botica.getByText('Cetirizina 10 mg').first().waitFor({ timeout: 15000 })
    await botica.getByRole('link', { name: 'Sí lo tengo: Cetirizina 10 mg' }).click(); await botica.waitForTimeout(1000)
    await botica.getByLabel('Precio por unidad').fill('5500')
    await botica.getByRole('button', { name: 'Enviar respuesta' }).click(); await botica.waitForTimeout(1500)
    await ana.getByText('Botica San José').first().waitFor({ timeout: 15000 })
    await ana.getByText('Droguería La 5').first().waitFor({ timeout: 15000 })
    await ana.waitForTimeout(1000)
  })
  const medios = async () => ana.getByRole('group', { name: '¿Cómo pagas?' }).getByRole('radio').evaluateAll(rs => rs.map(r => r.value))
  await paso('DEF-007', async () => {
    const elegir = async nombre => {
      const tarjeta = ana.locator('article, li').filter({ hasText: nombre }).first()
      await tarjeta.getByRole('link', { name: /Elegir/ }).or(tarjeta.getByRole('button', { name: /Elegir/ })).first().click()
      await ana.waitForTimeout(2000)
    }
    await elegir('Droguería La 5')
    out.def007la5 = await medios()
    await cap(ana, 'def007-confirmar-la5', 'DEF-007: Droguería La 5 (efectivo y transferencia) solo ofrece esos dos medios')
    await ana.goto(URL + '/solicitudes/' + out.solicitudAna); await ana.waitForTimeout(2500)
    await elegir('Botica San José')
    out.def007botica = await medios()
    await cap(ana, 'def007-confirmar-botica', 'DEF-007 · CP-TIE-012-01: Botica San José (efectivo y datáfono) no ofrece transferencia')
    await ana.getByText('Efectivo', { exact: true }).click()
    await ana.getByRole('button', { name: /Confirmar/ }).last().click(); await ana.waitForTimeout(2500)
    out.pedidoAna = ana.url()
    out.pedidoAnaTexto = await textoMain(ana)
  })
  await paso('DEF-009', async () => {
    await botica.goto(URL + '/tienda/pedidos'); await botica.waitForTimeout(2000)
    await botica.getByRole('link', { name: /Cetirizina 10 mg/ }).first().click(); await botica.waitForTimeout(2000)
    await cap(botica, 'def009-pedido-tienda', 'DEF-009: en el pedido que ve la tienda, «El cliente paga con efectivo.»')
    out.def009tienda = await textoMain(botica)
    await cap(ana, 'def009-pedido-cliente', 'DEF-009: el cliente sigue leyendo «Pagas con efectivo a la tienda.»')
  })
  await paso('DEF-008', async () => {
    const luis = await nuevo(b, 'luis@quienlotiene.test')
    await luis.goto(URL + '/solicitudes/nueva'); await luis.waitForTimeout(1500)
    await luis.getByRole('textbox', { name: '¿Qué estás buscando?' }).fill('Ibuprofeno 400 mg')
    await luis.getByRole('radio', { name: 'Farmacia' }).check()
    await luis.getByRole('radio', { name: /recojo/ }).check()
    await luis.getByRole('button', { name: 'Preguntar', exact: true }).click(); await luis.waitForTimeout(2500)
    await cap(luis, 'def008-esperando', 'DEF-008: recién publicada, «Esperando respuestas» con la hora de vencimiento')
    out.def008antes = await textoMain(luis)
    const id = execSync(`docker exec qa-db psql -U quienlotiene -d quienlotiene -tAc "select id from solicitudes.solicitud where producto='Ibuprofeno 400 mg'"`).toString().trim()
    out.def008id = id
    execSync(`docker exec qa-db psql -U quienlotiene -d quienlotiene -c "update solicitudes.solicitud set vence_en = now() - interval '1 second' where id='${id}'"`)
    await luis.getByRole('heading', { level: 1, name: 'Tu solicitud venció' }).waitFor({ timeout: 90000 })
    await luis.waitForTimeout(1500)
    await cap(luis, 'def008-vencida', 'DEF-008: con la pantalla abierta, al vencer dice «Tu solicitud venció» y que el plazo terminó')
    out.def008despues = await textoMain(luis)
    out.def008estadoBd = execSync(`docker exec qa-db psql -U quienlotiene -d quienlotiene -tAc "select estado from solicitudes.solicitud where id='${id}'"`).toString().trim()
  })
  fs.writeFileSync('reprueba-salida.json', JSON.stringify(out, null, 1))
  fs.writeFileSync('caps.json', JSON.stringify(caps, null, 1))
  await b.close()
})().catch(e => { console.error(e); process.exit(1) })
