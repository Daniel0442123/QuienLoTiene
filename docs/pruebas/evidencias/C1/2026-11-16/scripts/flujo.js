const { chromium, nuevo, cap, URL, caps } = require('./comun')
const fs = require('fs')
const out = {}
const PROD = process.env.PROD || 'Loratadina 10 mg'
async function paso(nombre, fn) { try { await fn() } catch (e) { console.log('FALLO PASO', nombre, e.message.split('\n')[0]) } }
;(async () => {
  const b = await chromium.launch()
  const la5 = await nuevo(b, 'drogueria5@quienlotiene.test')
  const botica = await nuevo(b, 'botica@quienlotiene.test')
  const popular = await nuevo(b, 'popular@quienlotiene.test')
  for (const t of [la5, botica, popular]) await t.goto(URL + '/tienda/solicitudes')
  await la5.waitForTimeout(2000)
  await cap(la5, 'tienda-sin-solicitudes', 'Droguería La 5 abierta y sin solicitudes; la página queda abierta, sin recargar')
  const ana = await nuevo(b, 'ana@quienlotiene.test')
  await ana.goto(URL + '/solicitudes/nueva'); await ana.waitForTimeout(1500)
  await paso('DEF-005', async () => {
    await ana.getByRole('button', { name: 'Preguntar', exact: true }).click()
    await cap(ana, 'cliente-publicar-vacio', 'Re-prueba DEF-005: «Preguntar» con el formulario vacío')
  })
  await paso('publicar', async () => {
    await ana.getByRole('textbox', { name: '¿Qué estás buscando?' }).fill(PROD)
    await ana.getByRole('radio', { name: 'Farmacia' }).check()
    await ana.getByRole('radio', { name: /^Casa/ }).check()
    await ana.getByRole('radio', { name: 'Domicilio' }).check()
    await ana.locator('summary').focus(); await ana.keyboard.press('Enter'); await ana.waitForTimeout(400)
    if (!(await ana.locator('details').evaluate(d => d.open))) await ana.locator('details').evaluate(d => { d.open = true })
    await ana.getByRole('textbox', { name: 'Cantidad' }).fill('2')
    await ana.getByRole('checkbox', { name: 'Lo necesito con urgencia' }).check()
    await cap(ana, 'cliente-publicar-lleno', 'Ana pide 2 «Loratadina 10 mg», Farmacia, a domicilio en «Casa», urgente')
    await ana.getByRole('button', { name: 'Preguntar', exact: true }).click()
    await ana.waitForTimeout(2500)
    out.solicitudUrl = ana.url()
    await cap(ana, 'cliente-esperando-respuestas', 'Solicitud publicada: «Esperando respuestas»')
  })
  await paso('tienda-ve-tiempo-real', async () => {
    await la5.getByText(PROD).first().waitFor({ timeout: 15000 })
    await cap(la5, 'tienda-solicitud-tiempo-real', 'CP-NOT-030-01/02 y CP-SOL-018-01/02: la solicitud llega sola (SSE), marcada Urgente, con distancia aproximada y sin datos del cliente')
    out.tarjetaLa5 = await la5.locator('main').innerText()
  })
  await paso('responder-si', async () => {
    await la5.getByRole('link', { name: `Sí lo tengo: ${PROD}` }).click()
    await la5.waitForTimeout(1000)
    out.urlResponderLa5 = la5.url()
    await la5.getByRole('button', { name: 'Enviar respuesta' }).click()
    await cap(la5, 'tienda-responder-sin-precio', 'Validación al responder «Sí lo tengo» sin precio')
    await la5.getByLabel('Precio por unidad').fill('9000')
    await cap(la5, 'tienda-responder-si-lleno', 'CP-SOL-019-01: «Sí lo tengo», $ 9.000 c/u, 2 unidades')
    await la5.getByRole('button', { name: 'Enviar respuesta' }).click()
    await la5.waitForTimeout(2000)
    await cap(la5, 'tienda-respuesta-enviada', 'Respuesta enviada')
  })
  await paso('responder-parecido', async () => {
    await botica.getByText(PROD).first().waitFor({ timeout: 15000 })
    await botica.getByRole('link', { name: `Tengo algo parecido: ${PROD}` }).click()
    await botica.waitForTimeout(1000)
    await botica.getByLabel('Precio por unidad').fill('7500')
    await botica.getByRole('button', { name: 'Enviar respuesta' }).click()
    await cap(botica, 'tienda-parecido-sin-descripcion', 'CP-SOL-019-02: «Tengo algo parecido» sin describir la alternativa')
    await botica.getByLabel('¿Qué ofreces en su lugar?').fill('Clarityne 10 mg (loratadina), caja x 10')
    await botica.getByRole('button', { name: 'Enviar respuesta' }).click()
    await botica.waitForTimeout(2000)
    await cap(botica, 'tienda-parecido-enviada', 'Botica San José envía la alternativa a $ 7.500 c/u')
  })
  await paso('responder-no', async () => {
    await popular.getByText(PROD).first().waitFor({ timeout: 15000 })
    await popular.getByRole('button', { name: `No lo tengo: ${PROD}` }).click()
    await popular.waitForTimeout(500)
    await cap(popular, 'tienda-no-lo-tengo', 'CP-SOL-019-03: «No lo tengo» en un toque, con opción de deshacer')
    await popular.waitForTimeout(8000)
  })
  await paso('duplicada', async () => {
    await la5.goto(out.urlResponderLa5); await la5.waitForTimeout(2000)
    await cap(la5, 'tienda-respuesta-duplicada', 'CP-SOL-019-04: al volver a la misma solicitud, la tienda ve que ya respondió')
  })
  await paso('cliente-respuestas', async () => {
    await ana.getByText('Droguería La 5').first().waitFor({ timeout: 15000 })
    await ana.getByText('Botica San José').first().waitFor({ timeout: 15000 })
    await ana.waitForTimeout(1500)
    await cap(ana, 'cliente-respuestas-tiempo-real', 'CP-SOL-020-01/03: las respuestas llegan sin recargar; la alternativa aparece marcada; sin botón de WhatsApp (CP-MEN-032-02)')
    out.respuestasAna = await ana.locator('main').innerText()
    out.whatsappAntes = await ana.getByRole('link', { name: /WhatsApp/ }).count()
    await ana.getByText('Precio', { exact: true }).first().click()
    await cap(ana, 'cliente-respuestas-por-precio', 'CP-SOL-020-02: ordenadas por precio')
    out.ordenPrecio = await ana.locator('main').innerText()
  })
  await paso('elegir', async () => {
    const tarjeta = ana.locator('article, li').filter({ hasText: 'Droguería La 5' }).first()
    await tarjeta.getByRole('link', { name: /Elegir/ }).or(tarjeta.getByRole('button', { name: /Elegir/ })).first().click()
    await ana.waitForTimeout(2000)
    await cap(ana, 'cliente-confirmar-pedido', 'Confirmar pedido: modalidad, dirección y solo los medios que acepta la tienda')
    out.confirmar = await ana.locator('main').innerText()
    await ana.getByText('Efectivo', { exact: true }).click()
    await cap(ana, 'cliente-confirmar-lleno', 'CP-ORD-024-01: domicilio a «Casa», efectivo; total = 2 × $ 9.000 + $ 5.000')
    await ana.getByRole('button', { name: /Confirmar/ }).last().click()
    await ana.waitForTimeout(2500)
    out.pedidoUrl = ana.url()
    await cap(ana, 'cliente-pedido-confirmado', 'Pedido creado en CONFIRMADO con botón de WhatsApp (CP-MEN-032-01)')
    out.pedidoAna = await ana.locator('main').innerText()
  })
  await paso('no-elegida', async () => {
    await botica.goto(URL + '/tienda/solicitudes/mis-respuestas'); await botica.waitForTimeout(2000)
    await cap(botica, 'tienda-no-elegida', 'CP-SOL-021-02: Botica San José ve su respuesta como «No elegida»')
    await la5.goto(URL + '/tienda/solicitudes/mis-respuestas'); await la5.waitForTimeout(2000)
    await cap(la5, 'tienda-elegida', 'Droguería La 5 ve su respuesta como «Elegida»')
  })
  await paso('tienda-pedido', async () => {
    await la5.goto(URL + '/tienda/pedidos'); await la5.waitForTimeout(2000)
    await cap(la5, 'tienda-pedidos', 'Pedidos de la tienda')
    await la5.getByRole('link', { name: new RegExp(PROD) }).first().click()
    await la5.waitForTimeout(2000)
    out.pedidoTiendaUrl = la5.url()
    await cap(la5, 'tienda-pedido-datos-cliente', 'CP-ORD-024-02: la tienda elegida ve nombre, teléfono y dirección de Ana')
    out.pedidoLa5 = await la5.locator('main').innerText()
    for (const [btn, nom, d] of [['Empezar a preparar', 'preparando', 'PREPARANDO'], ['Salió a domicilio', 'en-camino', 'EN_CAMINO'], ['Marcar como entregado', 'entregado', 'ENTREGADO']]) {
      await la5.getByRole('button', { name: btn }).click(); await la5.waitForTimeout(1500)
      await cap(la5, 'tienda-pedido-' + nom, `CP-ORD-027-01: la tienda avanza a ${d}`)
    }
    await ana.waitForTimeout(1500)
    await cap(ana, 'cliente-pedido-entregado', 'Ana ve el cambio a ENTREGADO sin recargar')
  })
  await paso('recibir', async () => {
    await ana.getByRole('button', { name: 'Recibí mi pedido' }).click(); await ana.waitForTimeout(2000)
    await cap(ana, 'cliente-pedido-recibido', 'CP-ORD-028-01: Ana confirma la recepción; la orden queda RESUELTA')
    await la5.waitForTimeout(1000); await la5.reload(); await la5.waitForTimeout(2500)
    await cap(la5, 'tienda-pedido-cerrado', 'Con el pedido cerrado la tienda deja de ver los datos del cliente')
  })
  fs.writeFileSync('flujo-salida.json', JSON.stringify(out, null, 1))
  fs.writeFileSync('caps.json', JSON.stringify(caps, null, 1))
  await b.close()
})().catch(e => { console.error(e); process.exit(1) })
